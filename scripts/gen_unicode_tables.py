#!/usr/bin/env python3
"""Generate src/util/unicode_tables.inc for util::LinearRegex.

The tables come from the Rust `regex-syntax` crate's `src/unicode_tables`
(generated by ucd-generate), so `\\p{..}`, `\\d \\w \\s`, word boundaries and
case-insensitive matching use exactly the Unicode data of the Rust regex
engine. Point --src at a regex-syntax checkout or crate directory.

Usage: python scripts/gen_unicode_tables.py --src <regex-syntax>/src/unicode_tables
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parents[1]
OUT = HERE / "src" / "util" / "unicode_tables.inc"

CHAR = r"'(?:\\u\{[0-9a-fA-F]+\}|\\x[0-9a-fA-F]{2}|\\[nrt0'\\]|[^'\\])'"
ESC = {"n": 0x0A, "r": 0x0D, "t": 0x09, "0": 0x00, "'": 0x27, "\\": 0x5C}


def char_value(tok: str) -> int:
    body = tok[1:-1]
    if body.startswith("\\u{"):
        return int(body[3:-1], 16)
    if body.startswith("\\x"):
        return int(body[2:], 16)
    if body.startswith("\\"):
        return ESC[body[1]]
    return ord(body)


def const_blocks(text: str) -> dict[str, str]:
    out = {}
    for m in re.finditer(r"pub const ([A-Z0-9_]+): [^=]+=\s*&\[(.*?)\];", text, re.S):
        out[m.group(1)] = m.group(2)
    return out


def ranges(block: str) -> list[tuple[int, int]]:
    return [(char_value(a), char_value(b))
            for a, b in re.findall(rf"\(({CHAR}), ({CHAR})\)", block)]


def by_name(blocks: dict[str, str]) -> list[tuple[str, list[tuple[int, int]]]]:
    pairs = re.findall(r'\("([^"]+)", ([A-Z0-9_]+)\)', blocks["BY_NAME"])
    return [(name, ranges(blocks[const])) for name, const in pairs]


def emit_ranges(rs: list[tuple[int, int]]) -> list[str]:
    out, row = [], []
    for a, b in rs:
        row.append(f"{{0x{a:X}, 0x{b:X}}}")
        if len(row) == 6:
            out.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        out.append("    " + ", ".join(row) + ",")
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", type=pathlib.Path, required=True,
                    help="regex-syntax src/unicode_tables directory")
    ap.add_argument("--out", type=pathlib.Path, default=OUT)
    args = ap.parse_args()

    def read(name: str) -> str:
        return (args.src / name).read_text(encoding="utf-8")

    version = re.search(r"Unicode version: ([0-9.]+?)\.?\n", read("general_category.rs")).group(1)
    sets: list[tuple[str, str, list[tuple[int, int]]]] = []
    for kind, fname in [("gc", "general_category.rs"), ("sc", "script.rs"),
                        ("scx", "script_extension.rs"), ("bool", "property_bool.rs"),
                        ("age", "age.rs"), ("gcb", "grapheme_cluster_break.rs"),
                        ("wb", "word_break.rs"), ("sb", "sentence_break.rs")]:
        for name, rs in by_name(const_blocks(read(fname))):
            sets.append((kind, name, rs))
    sets.append(("perl", "word", ranges(const_blocks(read("perl_word.rs"))["PERL_WORD"])))

    prop_names = re.findall(r'\("([^"]+)", "([^"]+)"\)',
                            const_blocks(read("property_names.rs"))["PROPERTY_NAMES"])

    values: list[tuple[str, str, str]] = []
    for m in re.finditer(r'\(\s*"([^"]+)",\s*&\[(.*?)\],\s*\)', read("property_values.rs"), re.S):
        for key, value in re.findall(r'\("([^"]+)", "([^"]+)"\)', m.group(2)):
            values.append((m.group(1), key, value))

    fold: list[tuple[int, list[int]]] = []
    for m in re.finditer(rf"\(({CHAR}), &\[([^\]]*)\]\)", read("case_folding_simple.rs")):
        fold.append((char_value(m.group(1)),
                     [char_value(t) for t in re.findall(CHAR, m.group(2))]))

    lines = [
        "// Generated by scripts/gen_unicode_tables.py from the Rust regex-syntax crate's",
        f"// Unicode {version} tables (MIT OR Apache-2.0). Do not edit by hand.",
        "// clang-format off",
        "",
        "namespace fastmcpp::util::unicode_tables",
        "{",
        "",
        f'inline constexpr const char* kUnicodeVersion = "{version}";',
        "",
        "struct Set",
        "{",
        "    const char* kind; // gc sc scx bool age gcb wb sb perl",
        "    const char* name; // canonical name",
        "    const char32_t (*ranges)[2];",
        "    unsigned count;",
        "};",
        "",
        "struct Name",
        "{",
        "    const char* key; // normalised (UAX44-LM3)",
        "    const char* value;",
        "};",
        "",
        "struct Value",
        "{",
        "    const char* property;",
        "    const char* key;",
        "    const char* value;",
        "};",
        "",
        "struct Fold",
        "{",
        "    char32_t c;",
        "    const char32_t* others;",
        "    unsigned count;",
        "};",
        "",
    ]
    for i, (_, _, rs) in enumerate(sets):
        lines.append(f"inline constexpr char32_t kSet{i}[][2] = {{")
        lines.extend(emit_ranges(rs or [(1, 0)]))
        lines.append("};")
    lines += ["", "inline constexpr Set kSets[] = {"]
    for i, (kind, name, rs) in enumerate(sets):
        lines.append(f'    {{"{kind}", "{name}", kSet{i}, {len(rs)}u}},')
    lines += ["};", "", "inline constexpr Name kPropertyNames[] = {"]
    for key, value in sorted(prop_names):
        lines.append(f'    {{"{key}", "{value}"}},')
    lines += ["};", "", "inline constexpr Value kPropertyValues[] = {"]
    for prop, key, value in sorted(values):
        lines.append(f'    {{"{prop}", "{key}", "{value}"}},')
    lines += ["};", ""]
    for i, (_, others) in enumerate(fold):
        lines.append(f"inline constexpr char32_t kFold{i}[] = {{"
                     + ", ".join(f"0x{o:X}" for o in others) + "};")
    lines += ["", "inline constexpr Fold kFold[] = {"]
    for i, (c, others) in enumerate(fold):
        lines.append(f"    {{0x{c:X}, kFold{i}, {len(others)}u}},")
    lines += ["};", "", "} // namespace fastmcpp::util::unicode_tables", "// clang-format on", ""]
    args.out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {args.out}: Unicode {version}, {len(sets)} sets, {len(prop_names)} names, "
          f"{len(values)} values, {len(fold)} fold entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
